package variables;

public class DecimalVariable {
	
	public static void main(String [] args) {
		
		//정수 번수 행성 실습 
		//byte, short, int, long 
		// 1byte == 2^8
		
		byte byteNumber = 1; //1byte --> 256 == -127 ~ 126 2^8
		
		short shortNumber = 4;// 2 ^ 16 
		
		int intNumber = 20; //2 ^ 32 
		
		long longNumber = 40000000000L ;// 2 ^ 64 
		
		
		
	}

}
