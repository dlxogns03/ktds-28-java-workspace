package variables;

public class FloatingNumberVariable {
	
	public static void main(String[] args) {
		
		//실수 (float, double)
		
		float floatNumber = 10.55F;
		float floatNumber1 = 10.0F;
		float floatNumber2 = 10;
		
		double doubleNumber = 11.123456789012345678901234567890 ;
		
		System.out.println(floatNumber);  //10.55
		System.out.println(floatNumber1); //10.0
		System.out.println(floatNumber2); //10.0
		
		System.out.println(doubleNumber);
		
	}
	
}
